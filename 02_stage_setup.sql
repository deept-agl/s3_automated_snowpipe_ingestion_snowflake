USE WAREHOUSE EVENTS_WH;
USE DATABASE EARTHQUAKE_DB;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS EARTHQUAKES_RAW (
  EVENT_DATA VARIANT,
  SOURCE_FILE VARCHAR
);

CREATE FILE FORMAT IF NOT EXISTS USGS_JSONL_FORMAT
  TYPE = JSON
  STRIP_OUTER_ARRAY = FALSE;

CREATE STAGE EARTHQUAKE_DB.RAW.USGS_S3_STAGE
  URL = 's3://earthquake-live-data-feed/earthquakes/incoming/'
  CREDENTIALS = (
     AWS_KEY_ID = ''
     AWS_SECRET_KEY = ''
  )
  FILE_FORMAT = EARTHQUAKE_DB.RAW.USGS_JSONL_FORMAT;