
USE WAREHOUSE EVENTS_WH;
USE DATABASE EARTHQUAKE_DB;
USE SCHEMA RAW;


CREATE PIPE IF NOT EXISTS EARTHQUAKE_DB.RAW.USGS_EARTHQUAKE_PIPE
  AUTO_INGEST = TRUE
AS
COPY INTO EARTHQUAKE_DB.RAW.EARTHQUAKES_RAW (EVENT_DATA, SOURCE_FILE)
FROM (
  SELECT $1, METADATA$FILENAME
  FROM @EARTHQUAKE_DB.RAW.USGS_S3_STAGE
)
FILE_FORMAT = (FORMAT_NAME = EARTHQUAKE_DB.RAW.USGS_JSONL_FORMAT)
ON_ERROR = SKIP_FILE;

