-- Dedicated compute and data storage for the earthquake ingestion workload.
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS WH_EARTHQUAKE_INGEST
 WAREHOUSE_SIZE = 'XSMALL'
 AUTO_SUSPEND = 60 
 AUTO_RESUME = TRUE 
 INITIALLY_SUSPENDED = TRUE;
 
CREATE DATABASE IF NOT EXISTS EARTHQUAKE_DB;
CREATE SCHEMA IF NOT EXISTS EARTHQUAKE_DB.BRONZE;

USE WAREHOUSE WH_EARTHQUAKE_INGEST;
USE DATABASE EARTHQUAKE_DB;
USE SCHEMA BRONZE;

CREATE TABLE IF NOT EXISTS EARTHQUAKES_RAW (
 EVENT_DATA VARIANT,
 SOURCE_FILE VARCHAR,
 LOAD_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE FILE FORMAT IF NOT EXISTS USGS_JSONL_FORMAT
TYPE = JSON 
STRIP_OUTER_ARRAY = FALSE;

-- Replace the example bucket name with your existing S3 bucket.
CREATE STORAGE INTEGRATION IF NOT EXISTS S3_EARTHQUAKE_INT
 TYPE = EXTERNAL_STAGE
 STORAGE_PROVIDER = 'S3'
 ENABLED = TRUE
 STORAGE_AWS_ROLE_ARN = '<AWS_ROLE_ARN>'
 STORAGE_ALLOWED_LOCATIONS = ('s3://<YOUR_BUCKET_NAME>/earthquakes/incoming/');

-- Use STORAGE_AWS_IAM_USER_ARN and STORAGE_AWS_EXTERNAL_ID in the AWS role trust policy.
-- Execute this command and locate the property_value for:
--   STORAGE_AWS_IAM_USER_ARN
--   STORAGE_AWS_EXTERNAL_ID
--   STORAGE_AWS_ROLE_ARN
-- Record the exact values. 
